// Local constructed outline contracts only: no provider, credentials or database.
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {blocks,renderDraft,DRAFT_VERSION} from '../src/domain/drafts.ts';
import {fixtures} from '../tests/analysis-fixtures.ts';

const snapshot={...fixtures[0].snapshot,confirmed:{confirmed_intent:'BUY',budget_min:1000000,budget_max:1500000,currency:'AED',locations:['Marina']},messages:[{...fixtures[0].snapshot.messages[0],body:'Please arrange a viewing and call me.'}]};
const groups=[];let failures=0;
for(const language of ['en','ar'])for(const tone of ['PROFESSIONAL','FRIENDLY']){
 let passed=0;
 for(const block of blocks){
  const evidence=['VIEWING_REQUEST','CALLBACK_REQUEST'].includes(block)?[{block,message_id:snapshot.messages[0].id,message_version:snapshot.messages[0].version,excerpt:snapshot.messages[0].body}]:[];
  try{
   const output=renderDraft({schema_version:DRAFT_VERSION,language,tone,blocks:[block],evidence},snapshot,{language,tone,instruction:''},['en','ar']);
   assert.equal(output.language,language);assert.equal(output.tone,tone);assert.deepEqual(output.safety_flags,[]);
   assert.ok(output.text.length>5&&output.text.length<=5000);
   if(block==='ACK_BUDGET')assert.ok(output.text.includes('1000000–1500000 AED'));
   if(block==='ACK_AREA')assert.ok(output.text.includes('Marina'));
   if(tone==='FRIENDLY')assert.ok(output.text.startsWith(language==='ar'?'مرحباً!':'Hello!'));
   passed++;
  }catch{failures++;}
 }
 groups.push({language,tone,total:blocks.length,passed});
}
const total=groups.reduce((n,g)=>n+g.total,0);
const report=`# P6 local reply contract evaluation

Generated by backend/scripts/evaluate-drafts.mjs on ${new Date().toISOString().slice(0,10)}. Prompt/schema: ${DRAFT_VERSION}.

This checks 56 constructed outline contracts: 14 maintained reply blocks across two languages and two tones. Assertions cover rendering, bounds, exact confirmed budget/area, language/tone and absence of lexical safety flags. No provider was called. This is not a measurement of model selection quality, Arabic fluency, complete conversation quality or customer usefulness.

| Language | Tone | Cases | Passed |
| --- | --- | ---: | ---: |
${groups.map(g=>`| ${g.language} | ${g.tone} | ${g.total} | ${g.passed} |`).join('\n')}

Separate automated tests cover missing facts, unsupported source requests, mismatched versions, malformed output, unsafe edits, SQL/domain safety parity, known/uncertain usage, shared quotas, stale results, assignment/membership changes, disabled processing, explicit review, immutable feedback, clipboard receipt expiry/replay and transactional rollback. Provider tests use injected responses; database tests emulate Auth with PGlite.

The live quality gate remains pending. Use approved deidentified inquiry samples with the configured model, record sample and language denominators, schema/model versions, selection failures and reviewer disagreements; review bilingual language and unsupported claims. Measure the proposed 70% sampled AI-suggestion usefulness target with a defined representative sample. Feedback entry counts and clipboard copies are not a usefulness percentage or sales probability. Hosted access/worker/latency/cost and browser clipboard/conflict journeys also need evidence. See REPLY_DRAFTS.md and PRODUCT_PLAN.md.

Result: ${total-failures}/${total} deterministic outline contracts passed.
`;
await writeFile(new URL('../../docs/REPLY_EVALUATION.md',import.meta.url),report);
console.log(`Reply contracts: ${total-failures}/${total} passed. Report: docs/REPLY_EVALUATION.md. No external calls.`);
if(failures)process.exitCode=1;
